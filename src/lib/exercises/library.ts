const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]));

export function findExercise(id: string): Exercise | undefined {
  return BY_ID.get(id);
}

/** True only if the athlete owns every piece of equipment the exercise needs. */
export function hasEquipment(exercise: Exercise, owned: Equipment[]): boolean {
  return exercise.equipment.every(
    (e) => e === "bodyweight" || owned.includes(e),
  );
}

export function exercisesFor(
  owned: Equipment[],
  predicate: (e: Exercise) => boolean,
): Exercise[] {
  return EXERCISES.filter((e) => hasEquipment(e, owned) && predicate(e));
}
